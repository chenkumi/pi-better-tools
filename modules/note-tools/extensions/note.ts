import { mkdir, open, realpath, rm } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { StringEnum } from "@earendil-works/pi-ai";
import { defineTool, withFileMutationQueue, type ExtensionAPI } from "@earendil-works/pi-coding-agent";
import { Type } from "typebox";
import { Text } from "@earendil-works/pi-tui";
import { stripVTControlCharacters } from "node:util";

const displayText = (value: unknown, max = 2000) => typeof value === "string"
  ? stripVTControlCharacters(value.slice(0, max * 4)).replace(/\r\n?/g, "\n").replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f\u202a-\u202e\u2066-\u2069]/g, "").slice(0, max) : "";

/** Generous UTF-8 byte cap for one note (a note is a document, not a data dump). */
export const MAX_NOTE_BYTES = 8 * 1024 * 1024;

const noteTypes = ["plan", "design", "issue", "research", "report", "task"] as const;
const noteDirectories = { plan: "plans", design: "designs", issue: "issues", research: "research", report: "reports", task: "tasks" } as const satisfies Record<(typeof noteTypes)[number], string>;

/**
 * Compare whole path segments: a directory literally named "..archive" is inside the workspace, "../x" is not.
 * The workspace root itself is inside (a note folder may be a link back to it); only leaving the workspace is an escape.
 */
function isOutsideWorkspace(cwd: string, directory: string): boolean {
  const inside = relative(cwd, directory);
  return inside === ".." || inside.startsWith(".." + sep) || isAbsolute(inside);
}

type NoteType = (typeof noteTypes)[number];
const MAX_FILENAME_ATTEMPTS = 1000;

/** Errors raised by this module's own checks; anything else is a raw filesystem error that gets wrapped. */
class NoteError extends Error {}
/** Raised only by this module's own containment checks, so cleanup never mistakes a filesystem error for one. */
class NoteDirectoryEscapeError extends NoteError {}

/** Bounded rendering of a received value for error messages. */
const received = (value: unknown): string => typeof value === "string"
  ? JSON.stringify(value.length > 40 ? value.slice(0, 40) + "..." : value)
  : value === null ? "null" : Array.isArray(value) ? "array" : typeof value;

const escapeMessage = (folder: string, detail: string) =>
  `NOTE_DIRECTORY_ESCAPE: ${folder}/ ${detail} The note path is system-generated and cannot be changed, and retrying will fail the same way: ask the user to remove or retarget the ${folder}/ link so it stays inside the workspace.`;

/** Wrap a raw fs error with the operation, relative folder and a hint; the absolute workspace path is replaced by ".". */
function writeFailure(error: unknown, operation: string, folder: string, cwd: string): Error {
  const raw = error instanceof Error ? error.message : String(error);
  const code = error && typeof error === "object" && "code" in error && typeof error.code === "string" ? error.code : "unknown";
  const safe = raw.split(cwd).join(".").split(cwd.replaceAll("\\", "/")).join(".");
  return new Error(`NOTE_WRITE_FAILED: ${operation} ${folder}/ failed (${code}): ${safe}. Check that ${folder}/ in the workspace is a writable directory (not a regular file), that there is free disk space and permission to write, then call note again.`, { cause: error });
}

/** Also protects direct/programmatic callers that bypass the host's schema validation. */
function validateNote(params: { type: NoteType; content: string }): void {
  const unsupported = Object.keys(params).filter(key => key !== "type" && key !== "content");
  if (unsupported.length > 0) {
    const names = unsupported.slice(0, 5).map(key => JSON.stringify(key.length > 40 ? key.slice(0, 40) + "..." : key)).join(", ");
    throw new NoteError(`NOTE_INVALID_ARGUMENTS: unsupported parameter(s) ${names}${unsupported.length > 5 ? ", ..." : ""}. Only "type" and "content" are accepted; the file name and folder are generated by the tool (put any title inside content as a Markdown heading).`);
  }
  if (!noteTypes.includes(params.type)) {
    throw new NoteError(`NOTE_INVALID_ARGUMENTS: parameter "type" must be one of ${noteTypes.join(", ")} (received ${received(params.type)}).`);
  }
  if (typeof params.content !== "string") {
    throw new NoteError(`NOTE_INVALID_ARGUMENTS: parameter "content" must be a string containing the full Markdown document (received ${received(params.content)}).`);
  }
  const surrogate = params.content.search(/[\uD800-\uDFFF]/u);
  if (surrogate >= 0) {
    throw new NoteError(`NOTE_INVALID_ARGUMENTS: parameter "content" contains a lone UTF-16 surrogate at index ${surrogate}; remove it (or replace it with a valid character) and call note again.`);
  }
  const bytes = Buffer.byteLength(params.content, "utf8");
  if (bytes > MAX_NOTE_BYTES) {
    throw new NoteError(`NOTE_TOO_LARGE: parameter "content" is ${bytes} bytes (UTF-8), limit ${MAX_NOTE_BYTES} (8 MiB); split it into several notes, one call each.`);
  }
  if (params.content.trim() === "") {
    throw new NoteError("NOTE_EMPTY: content is empty or whitespace only. Write the complete Markdown document (with a title heading) into content and call note again.");
  }
}

/** <cwd>/<folder>, created if needed. It may be a pre-existing symlink/junction; refuse one that leads outside the workspace. */
async function prepareNoteDirectory(cwd: string, folder: string): Promise<string> {
  const directory = resolve(cwd, folder);
  let realDirectory: string, realCwd: string;
  try {
    await mkdir(directory, { recursive: true });
    [realCwd, realDirectory] = await Promise.all([realpath(cwd), realpath(directory)]);
  } catch (error) { throw writeFailure(error, "creating folder", folder, cwd); }
  if (isOutsideWorkspace(realCwd, realDirectory)) {
    throw new NoteDirectoryEscapeError(escapeMessage(folder, "is a symlink or junction that resolves outside the workspace; refusing to write."));
  }
  return directory;
}

/** TYPE-YYYYMMDDTHHmmssSSSZ.md (UTC). */
const noteFilename = (type: NoteType, time: number) => `${type.toUpperCase()}-${new Date(time).toISOString().replace(/[-:.]/g, "")}.md`;

/** Real locations of cwd and the just-created file, or undefined when they cannot be resolved (e.g. a racing swap). */
async function createdLocation(cwd: string, path: string): Promise<{ cwd: string; file: string } | undefined> {
  try {
    const [realCwd, file] = await Promise.all([realpath(cwd), realpath(path)]);
    return { cwd: realCwd, file };
  } catch { return undefined; }
}

/** Creates `path` exclusively and writes `content`; throws EEXIST when the name is taken. */
async function createNoteFile(path: string, content: string, cwd: string, folder: string, signal: AbortSignal | undefined): Promise<void> {
  await withFileMutationQueue(path, async () => {
    signal?.throwIfAborted();
    // Exclusive creation is the cross-process no-overwrite guard. Do not cancel
    // mid-write: once started, finish writing and report the resulting path.
    const handle = await open(path, "wx", 0o644);
    try {
      // Post-create re-verification: if <cwd>/<folder> was swapped for a junction/symlink after the check above,
      // the empty file we just created landed outside the workspace. Remove it (it is ours, created with wx)
      // before any content is written. A location that cannot be resolved is not verified and fails closed the same way.
      // Narrows the window; it is not an atomic guarantee against a persistent attacker.
      const location = await createdLocation(cwd, path);
      if (!location || isOutsideWorkspace(location.cwd, dirname(location.file))) {
        await handle.close().catch(() => {});
        await rm(location?.file ?? path, { force: true }).catch(() => {});
        throw new NoteDirectoryEscapeError(location
          ? escapeMessage(folder, "resolved outside the workspace during creation (it was swapped for a link); the file was removed.")
          : escapeMessage(folder, "could not be re-verified inside the workspace during creation; the file was removed."));
      }
      await handle.writeFile(content, "utf8");
    }
    catch (error) {
      if (error instanceof NoteDirectoryEscapeError) throw error;
      // We created this file (wx), so a partial result from e.g. ENOSPC is ours to remove.
      await handle.close().catch(() => {});
      await rm(path, { force: true }).catch(() => {});
      throw error;
    }
    await handle.close();
  });
}

export const noteTool = defineTool({
  name: "note",
  label: "Note",
  description:
    "Save a NEW Markdown document as plan, design, issue, research, report or task. Required for such documents: do NOT use write and do NOT choose a file name or folder. " +
    "The tool picks <cwd>/<folder>/TYPE-YYYYMMDDTHHmmssSSSZ.md (UTC; no title suffix), never overwrites, and returns the path; send the complete document in one call. " +
    "Use it when asked to write down, record, save or log such a document, or when finished work deserves a record. Not for source code or existing files: to change a note afterwards use read/edit on the returned path.",
  promptSnippet: "Save a new plan/design/issue/research/report/task Markdown document; file name is auto-generated and the saved path is returned.",
  promptGuidelines: [
    "Create plan/design/issue/research/report/task documents with note { type, content }, not write.",
  ],
  annotations: { readOnlyHint: false, destructiveHint: false, idempotentHint: false, openWorldHint: false },
  parameters: Type.Object({
    type: StringEnum(noteTypes, { description: "Category (saved under its plural folder: plans/designs/issues/research/reports/tasks): plan = approach/steps/roadmap; design = design document (architecture, interfaces, decisions); issue = bug/problem/risk; research = findings; report = results/summary/review; task = to-do." }),
    content: Type.String({ description: "The full Markdown document, including a title heading, written verbatim. Do not include a file name." }),
  }, { additionalProperties: false }),
  outputSchema: Type.Object({
    relativePath: Type.String(),
  }, { additionalProperties: false }),
  renderCall(args, theme, context) {
    const type = displayText(args?.type, 20) || "…";
    const title = displayText(args?.content, 300).split("\n").find(line => line.trim())?.replace(/^#+\s*/, "").slice(0, 100) || "";
    const bytes = typeof args?.content === "string" ? Buffer.byteLength(args.content, "utf8") : 0;
    const component = context.lastComponent instanceof Text ? context.lastComponent : new Text("", 0, 0);
    component.setText(`${theme.fg("toolTitle", theme.bold("note"))} ${theme.fg("accent", type)}${title ? ` · ${theme.fg("muted", title)}` : ""}\n${theme.fg("muted", `${context.argsComplete ? "received" : "receiving"} ${bytes.toLocaleString("en-US")} bytes`)}`);
    return component;
  },
  renderResult(result, { isPartial }, theme, context) {
    const text = result.content.filter(block => block.type === "text").map(block => block.text).join("\n");
    if (context.isError) return new Text(theme.fg("error", `Note failed\n${displayText(text)}`), 0, 0);
    if (isPartial) return new Text(theme.fg("muted", "Saving note…"), 0, 0);
    const saved = result.details as Partial<{ relativePath: string }> | undefined;
    const path = displayText(saved?.relativePath);
    return new Text(theme.fg("success", path ? `Saved note: ${path}` : displayText(text) || "Note result unavailable"), 0, 0);
  },
  async execute(_toolCallId, params, signal, _onUpdate, ctx) {
    validateNote(params);
    signal?.throwIfAborted();
    const folder = noteDirectories[params.type];
    const directory = await prepareNoteDirectory(ctx.cwd, folder);
    const timestamp = Date.now();
    for (let attempt = 0; attempt < MAX_FILENAME_ATTEMPTS; attempt++) {
      const filename = noteFilename(params.type, timestamp + attempt);
      try {
        await createNoteFile(join(directory, filename), params.content, ctx.cwd, folder, signal);
      } catch (error) {
        if (error && typeof error === "object" && "code" in error && error.code === "EEXIST") continue;
        if (error instanceof NoteError || signal?.aborted || (error instanceof Error && error.name === "AbortError")) throw error;
        throw writeFailure(error, "writing a note in", folder, ctx.cwd);
      }
      const saved = { relativePath: `${folder}/${filename}` };
      return {
        content: [{ type: "text", text: `Saved note: ${saved.relativePath} (relative to cwd; use read/edit on this path to change it)` }],
        details: saved,
        structuredContent: saved,
      };
    }
    throw new NoteError(`NOTE_FILENAME_COLLISION: Could not allocate a new filename after ${MAX_FILENAME_ATTEMPTS} attempts. Retry the call.`);
  },
});

export default function noteExtension(pi: ExtensionAPI) {
  pi.registerTool(noteTool);
}
